// Makes live/tcvoices.js: every Three Cities sound, lifted straight out of /index.html so the two never drift apart.
// Run it again after the sounds change in Three Cities:   node build_voices.mjs
import fs from 'fs';
const src = fs.readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const between = (a, b, from = 0) => { const i = src.indexOf(a, from); if (i < 0) throw new Error('missing ' + a); const j = src.indexOf(b, i); if (j < 0) throw new Error('missing ' + b); return src.slice(i, j); };
const upTo = (a, closer) => { const i = src.indexOf(a); if (i < 0) throw new Error('missing ' + a); const j = src.indexOf('\n' + closer + '\n', i); return src.slice(i, j + closer.length + 1); };
const helpers = between('  let noiseBuf = null;', '  function setupAudio() {').replace('let noiseBuf = null;', '');
const gains = between('  const mtof = m =>', '  // awake while the other two sleep');
const perc = between('  const SAMPLE_USER_G', '  // Perform mode can soften');
const core = upTo('  function voiceCore(', '  }');
const sounds = between('  const SOUNDS = [', '  // The menu, sorted into families');
const names = between('  const SOUND_NAME = ', '  const KEYS = ');
const scales = between('  const KEYS = ', 'const SCALES = [') + upTo('  const SCALES = [', '  ];');
const body = (helpers + gains + perc + core).replace(/dir: "samples\//g, 'dir: "/samples/');
const out = `/* Every Three Cities sound, for the Rhythm Geometry performance pages.
   GENERATED by build_voices.mjs from /index.html. Do not edit by hand. Run: node build_voices.mjs */
window.TCVoices = function (ac) {
  'use strict';
  let noiseBuf = ac.createBuffer(1, ac.sampleRate, ac.sampleRate);
  { const d = noiseBuf.getChannelData(0); for (let i = 0; i < d.length; i++) d[i] = Math.random() * 2 - 1; }
  const buses = { get: c => c._bus };
  const loneAwake = () => false;
${body}
  function voice(c, midi, vel, t, L = 1) { voiceCore(c, midi, vel, t, L); }
${sounds}${names}
  const SOUND_LIST = SOUND_GROUPS.filter(g => g[0] !== 'Your own');
${scales}
  const NEED_OF = NEEDS;
  return {
    // a voice slot for one ring: it plays into dest
    make(dest) { return { voice: 'felt', steps: 16, pos: 0, shape: null, samp: null, sampShape: {}, w: { r: 1, w: 12, t: 12, h: 60 }, _bus: { input: dest, chorusIn: null } }; },
    play(c, name, midi, vel, t, L) { c.voice = name; voice(c, midi, vel, t, L); },
    preload(name) { if (NEED_OF[name]) loadSamples(NEED_OF[name]); },
    groups: SOUND_LIST, name: SOUND_NAME, keys: KEYS, scales: SCALES
  };
};
`;
fs.writeFileSync(new URL('./live/tcvoices.js', import.meta.url), out);
console.log('tcvoices.js', out.length, 'bytes');
